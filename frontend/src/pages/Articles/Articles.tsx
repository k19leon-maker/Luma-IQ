// ─── Form component ───────────────────────────────────────────────────────────

const PLATFORMS = [
  { key: 'dzen',     label: 'Яндекс Дзен' },
  { key: 'vc',       label: 'VC.ru' },
  { key: 'telegraf', label: 'Телеграф' },
  { key: 'other',    label: 'Другая' },
];

function ArticlesForm({ onGenerate, loading }: FormProps) {
  const [platform, setPlatform] = useState('dzen');
  const [topic,    setTopic]    = useState('');

  const handleGenerate = () => {
    const title = topic.trim() || 'Новая статья';
    onGenerate(title, getMockArticle(platform, title));
  };

  return (
    <>
      <h2 className={s.formTitle}>Новая статья</h2>

      <div className={s.formField}>
        <span className={s.chipLabel}>Площадка</span>
        <div className={s.chipGroup}>
          {PLATFORMS.map(({ key, label }) => (
            <button
              key={key}
              className={`${s.chip}${platform === key ? ' ' + s.chipActive : ''}`}
              onClick={() => setPlatform(key)}
            >
              {label}
            </button>
          ))}
        </div>
      </div>

      <div className={s.formField}>
        <label className={s.formLabel}>Тема статьи</label>
        <input
          className={s.formInput}
          placeholder="Например: Почему пары не могут договориться"
          value={topic}
          onChange={(e) => setTopic(e.target.value)}
        />
      </div>

      <button className={s.generateBtn} onClick={handleGenerate} disabled={loading}>
        {loading ? <><span className={s.spinner} /> Генерирую...</> : 'Сгенерировать структуру →'}
      </button>
    </>
  );
}

// ─── Page ─────────────────────────────────────────────────────────────────────

export default function Articles() {
  return (
    <ContentWorkspace
      sectionTitle="Статьи"
      initialMaterials={SEED}
      FormComponent={ArticlesForm}
    />
  );
}

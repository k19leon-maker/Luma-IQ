async function callAnthropic(req: AIRequest): Promise<AIResponse> {
  const { default: Anthropic } = await import('@anthropic-ai/sdk');
  const client = new Anthropic({ apiKey: env.ANTHROPIC_API_KEY });

  const systemPrompt =
    req.systemPrompt ??
    (req.section && SYSTEM_PROMPTS[req.section] ? SYSTEM_PROMPTS[req.section] : PSY_BOOST_SYSTEM_PROMPT);

  if (req.section && SYSTEM_PROMPTS[req.section]) {
    console.log(`📌 Используется промпт для раздела: ${req.section}`);
  }

  try {
    const model = req.claudeModel ?? 'claude-haiku-4-5-20251001';
    if (req.claudeModel) console.log(`🤖 Используется модель: ${model}`);

    const response = await client.messages.create({
      model,
      max_tokens: req.maxTokens ?? 1024,
      system: systemPrompt,
      messages: req.messages
        .filter((m) => m.role !== 'system')
        .map((m) => ({ role: m.role as 'user' | 'assistant', content: m.content })),
    });

    console.log('✅ Claude API: реальный ответ получен');

    const block = response.content[0];
    const content = block.type === 'text' ? block.text : '';

    return { content, provider: 'anthropic', mock: false };
  } catch (err: unknown) {
    const e = err as { status?: number; message?: string };
    console.error('[AIService] Anthropic error:', e.status, e.message);
    if (e.status === 402) {
      throw new Error('Недостаточно средств на балансе API');
    }
    throw new Error('Ошибка соединения с ИИ. Попробуйте ещё раз.');
  }
}

